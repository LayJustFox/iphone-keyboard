    private static String[][] cache;

    /** Category emoji lists, filtered to what this phone can display. */
    static synchronized String[][] categories() {
        if (cache != null) return cache;
        Paint p = new Paint();
        String[] raw = {SMILEYS, ANIMALS, FOOD, ACTIVITY, TRAVEL, OBJECTS, SYMBOLS, null};
        String[][] out = new String[raw.length][];
        for (int i = 0; i < raw.length; i++) {
            ArrayList<String> list = new ArrayList<>();
            if (raw[i] != null) {
                addAll(list, raw[i], p);
            } else {
                addAll(list, SPECIAL_FLAGS, p);
                for (String code : FLAG_CODES.split(" ")) {
                    String f = flag(code);
                    if (!list.contains(f) && p.hasGlyph(f)) list.add(f);
                }
            }
            out[i] = list.toArray(new String[0]);
        }
        cache = out;
        return out;
    }

    static String[] filter(java.util.List<String> items) {
        Paint p = new Paint();
        ArrayList<String> list = new ArrayList<>();
        for (String s : items) if (p.hasGlyph(s)) list.add(s);
        return list.toArray(new String[0]);
    }

    private static void addAll(ArrayList<String> list, String s, Paint p) {
        for (String e : s.split(" ")) {
            if (!e.isEmpty() && p.hasGlyph(e)) list.add(e);
        }
    }

    static String flag(String code) {
        int a = 0x1F1E6 + (code.charAt(0) - 'A');
        int b = 0x1F1E6 + (code.charAt(1) - 'A');
        return new String(Character.toChars(a)) + new String(Character.toChars(b));
    }
